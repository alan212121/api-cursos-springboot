-- Script de la base de datos cursos_db (PostgreSQL 11 o superior)
-- Ejecutar en el Query Tool de pgAdmin, conectado a la base cursos_db.
-- Crea las 8 tablas y completa 2000 registros por tabla (3 en rol).
-- Se puede ejecutar mas de una vez sin duplicar datos.

-- 1) TABLAS
CREATE TABLE IF NOT EXISTS idioma (
    id_idioma integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(40), codigo varchar(10));
CREATE TABLE IF NOT EXISTS nivel (
    id_nivel integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(30));
CREATE TABLE IF NOT EXISTS modalidad (
    id_modalidad integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(30));
CREATE TABLE IF NOT EXISTS tipo_curso (
    id_tipo_curso integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(60));
CREATE TABLE IF NOT EXISTS estado (
    id_estado integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(30));
CREATE TABLE IF NOT EXISTS rol (
    id_rol integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(50) NOT NULL UNIQUE);
CREATE TABLE IF NOT EXISTS usuario (
    id_usuario integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(120), correo varchar(120), genero varchar(20),
    telefono varchar(20), password_hash varchar(255),
    activo boolean DEFAULT true, creado_en timestamp DEFAULT now(),
    id_rol integer NOT NULL REFERENCES rol(id_rol));
CREATE TABLE IF NOT EXISTS solicitud_arco (
    id_solicitud integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario integer NOT NULL REFERENCES usuario(id_usuario),
    tipo_derecho varchar(20) NOT NULL,
    detalles text,
    estado varchar(30) NOT NULL DEFAULT 'PENDIENTE',
    fecha_solicitud timestamp NOT NULL DEFAULT now(),
    fecha_respuesta timestamp,
    codigo varchar(64),
    expira_en timestamp);

-- 2) ROLES
INSERT INTO rol (nombre) VALUES ('ROLE_ADMIN'), ('ROLE_MAESTRO'), ('ROLE_ALUMNO')
ON CONFLICT (nombre) DO NOTHING;

-- 3) COMPLETAR HASTA 2000 REGISTROS POR TABLA
INSERT INTO idioma (nombre, codigo)
SELECT 'Idioma ' || g, 'I' || g
FROM generate_series(1, GREATEST(0, 2000 - (SELECT COUNT(*) FROM idioma))) g;

INSERT INTO nivel (nombre)
SELECT 'Nivel ' || g
FROM generate_series(1, GREATEST(0, 2000 - (SELECT COUNT(*) FROM nivel))) g;

INSERT INTO modalidad (nombre)
SELECT 'Modalidad ' || g
FROM generate_series(1, GREATEST(0, 2000 - (SELECT COUNT(*) FROM modalidad))) g;

INSERT INTO tipo_curso (nombre)
SELECT 'Tipo de curso ' || g
FROM generate_series(1, GREATEST(0, 2000 - (SELECT COUNT(*) FROM tipo_curso))) g;

INSERT INTO estado (nombre)
SELECT 'Estado ' || g
FROM generate_series(1, GREATEST(0, 2000 - (SELECT COUNT(*) FROM estado))) g;

INSERT INTO usuario (nombre, correo, genero, telefono, password_hash,
                     activo, creado_en, id_rol)
SELECT 'Usuario ' || g,
       'usuario' || g || '@correo.com',
       (ARRAY['Masculino','Femenino','Otro'])[1 + g % 3],
       '55' || LPAD(g::text, 8, '0'),
       encode(sha256(convert_to('pass' || g, 'UTF8')), 'hex'),
       true,
       now() - (g % 365) * interval '1 day',
       (SELECT id_rol FROM rol WHERE nombre = CASE
            WHEN g % 50 = 0 THEN 'ROLE_ADMIN'
            WHEN g % 10 = 0 THEN 'ROLE_MAESTRO'
            ELSE 'ROLE_ALUMNO' END)
FROM generate_series(1, GREATEST(0, 2000 - (SELECT COUNT(*) FROM usuario))) g;

INSERT INTO solicitud_arco (id_usuario, tipo_derecho, detalles, estado,
                            fecha_solicitud)
SELECT u.id_usuario,
       (ARRAY['ACCESO','RECTIFICACION','CANCELACION','OPOSICION'])
           [1 + (u.id_usuario % 4)],
       'Solicitud de ejemplo numero ' || u.id_usuario,
       (ARRAY['PENDIENTE','EN_PROCESO','COMPLETADO','RECHAZADO'])
           [1 + ((u.id_usuario / 4) % 4)],
       now() - (u.id_usuario % 90) * interval '1 day'
FROM usuario u
ORDER BY u.id_usuario DESC
LIMIT GREATEST(0, 2000 - (SELECT COUNT(*) FROM solicitud_arco));
